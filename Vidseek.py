def build_knowledge_graph(df: pd.DataFrame) -> nx.Graph:
    G = nx.Graph()
    print("Building Knowledge Graph...")
    for _, row in df.iterrows():
        video_id = str(row['camera_media_id'])
        G.add_node(video_id, type='video')

        # Add and link nodes for events, objects, etc., standardized to lowercase
        if pd.notna(row['event_type']):
            node = str(row['event_type']).lower().strip()
            G.add_node(node, type='event')
            G.add_edge(video_id, node)
        try:
            if pd.notna(row['objects_seen']):
                objects = json.loads(str(row['objects_seen']).replace("'", "\""))
                for obj in objects:
                    node = obj.lower().strip()
                    G.add_node(node, type='object')
                    G.add_edge(video_id, node)
        except:
            pass
    print(f"Knowledge Graph built: {G.number_of_nodes()} nodes, {G.number_of_edges()} edges.")
    return G

