def build_pipeline(df: pd.DataFrame) -> Dict:
    df['video_id'] = df['camera_media_id'].astype(str)

    # Generate descriptions (assuming Claude for best results)
    print("Generating video descriptions with Claude...")
    desc = [claude_describe_row(r[1]) for r in df.iterrows()]
    meta = pd.DataFrame({'video_id': df['video_id'], 'phrase': desc})

    # Build semantic search assets
    embedder = Embedder(Config.EMBED_MODEL)
    vecs = embedder.encode(meta['phrase'].tolist())
    index = build_faiss_index(vecs)

    # Build knowledge graph
    graph = build_knowledge_graph(df)

    return {'meta': meta, 'index': index, 'embedder': embedder, 'graph': graph, 'df': df}

# =============================
# NEW: Hybrid Search and Preview Logic
# =============================
def hybrid_search_and_preview(queries: List[str], assets: Dict):
    meta, index, embedder, graph, df = assets['meta'], assets['index'], assets['embedder'], assets['graph'], assets['df']

    for q in queries:
        print(f"\n=== Hybrid Search Query: \"{q}\" ===")

        # --- Stage 1: Semantic Retrieval ---
        q_vec = embedder.encode([q], is_query=True)
        scores, indices = index.search(q_vec, Config.TOPK_RETRIEVAL)

        candidates = []
        for score, idx in zip(scores[0], indices[0]):
            if idx < 0: continue
            candidates.append({
                'id': meta.iloc[int(idx)].video_id,
                'semantic_score': score
            })

        # --- Stage 2: Graph Re-ranking ---
        target_nodes = claude_parse_query(q)
        print(f"Parsed graph entities for re-ranking: {target_nodes}")

        re_ranked_results = []
        for cand in candidates:
            graph_matches = 0
            if target_nodes:
                for neighbor in graph.neighbors(cand['id']):
                    if neighbor in target_nodes:
                        graph_matches += 1
                graph_score = graph_matches / len(target_nodes)
            else:
                graph_score = 0

            # Combine scores
            final_score = (Config.SEMANTIC_WEIGHT * cand['semantic_score']) + \
                          (Config.GRAPH_WEIGHT * graph_score)

            re_ranked_results.append({**cand, 'graph_score': graph_score, 'final_score': final_score})

        # Sort by the new final score
        re_ranked_results.sort(key=lambda x: x['final_score'], reverse=True)

        # --- Display Top Results ---
        for result in re_ranked_results[:Config.TOPK_FINAL]:
            vid = result['id']
            phr = meta[meta['video_id'] == vid].phrase.iloc[0]

            print(f"Video {vid} | Final Score: {result['final_score']:.3f} (Semantic: {result['semantic_score']:.2f}, Graph: {result['graph_score']:.2f})")
            print(f"Tags: {phr}")

            render_s3_video(vid, width=300)

            # Display full description
            row = df[df['camera_media_id'].astype(str) == vid].iloc[0]
            desc = claude_describe_row(row) if Config.USE_CLAUDE else phr
            print(f"Description: {desc}\n")

